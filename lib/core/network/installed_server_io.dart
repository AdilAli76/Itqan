import 'dart:io' show File, Platform;

/// يقرأ `server.txt` بجوار الملف التنفيذي — سطرٌ واحد فيه عنوان الخادم.
///
/// **الحاجة التي يسدّها:** النسخة المحلّية بلا إنترنت تعمل على جهاز المحلّ
/// نفسه، وعنوانها معلومٌ لحظةَ التركيب. وبلا هذا كان الزبون يُقابَل بشاشة
/// «أدخل عنوان الخادم» في أوّل فتحة — سؤالٌ لا يعرف جوابه عن جهازٍ أمامه.
///
/// **ولماذا ملفٌّ لا خبزٌ وقت البناء:** الخبز يعني نسختين من التطبيق
/// تُبنيان وتُوقَّعان وتُختبران، بينما الفرق سطرٌ نصّي. وهو عين ما أُصلح في
/// الأندرويد من قبل — «نسخة APK لكل عميل».
///
/// **ومتزامنة عمداً:** تُستدعى قبل `runApp`، وقراءةُ ملفٍّ صغير محلّي أسرع
/// من إطارٍ واحد. وجعلُها غير متزامنة كانت تعني وميض شاشة الإعداد ثم
/// اختفاءها.
///
/// **وتبتلع كل أخطائها:** الملف اختياري بطبيعته — غيابه هو الحالة الطبيعية
/// في النسخة المتّصلة بخادمٍ بعيد، ولا يصحّ أن يُسقط الإقلاع.
String? readInstalledServer() {
  try {
    final dir = File(Platform.resolvedExecutable).parent.path;
    final file = File('$dir${Platform.pathSeparator}server.txt');
    if (!file.existsSync()) return null;

    // أوّل سطرٍ غير فارغ ولا تعليق: ملفٌّ يُحرَّر بالمفكّرة يُكتب فيه شرحٌ
    // فوق العنوان، وقراءتُه كلّه تُنتج عنواناً لا يعمل.
    for (final raw in file.readAsLinesSync()) {
      final line = raw.trim();
      if (line.isEmpty || line.startsWith('#')) continue;
      return line;
    }
    return null;
  } catch (_) {
    return null;
  }
}
