import 'package:flutter/foundation.dart';

/// «الآن» عبر نقطة واحدة، ليمكن تثبيته في الاختبارات.
///
/// **العطب الذي يصلحه:** لقطات الشاشات المرجعية كانت تسقط **كل منتصف ليل**.
/// شاشة التقارير تعرض «عدد الأيام منذ كذا»، وشاشة المخزون تعرض «تنتهي خلال
/// كذا يوماً» — وكلاهما محسوب من `DateTime.now()` على عيّنات ثابتة التواريخ.
/// فتتغيّر الصورة يومياً بلا أن يتغيّر سطر واحد من الكود.
///
/// وفشلٌ يومي كاذب أسوأ من غياب الاختبار: من يراه كل صباح يتوقّف عن قراءته،
/// فيمرّ الفشل الحقيقي معه.
///
/// <para><b>ولماذا هنا لا في كل موضع:</b> النظام يستدعي `DateTime.now()` في
/// عشرات المواضع، وأكثرها يكتب طابعاً زمنياً لا يُعرَض. المقصود هنا ما
/// **يُرسَم على الشاشة ويتغيّر بمرور اليوم** — وهو ما تُقارنه اللقطات.</para>
class AppClock {
  const AppClock._();

  static DateTime? _frozen;

  static DateTime now() => _frozen ?? DateTime.now();

  /// يثبّت الوقت — للاختبارات وحدها.
  @visibleForTesting
  static void freeze(DateTime at) => _frozen = at;

  @visibleForTesting
  static void unfreeze() => _frozen = null;
}
